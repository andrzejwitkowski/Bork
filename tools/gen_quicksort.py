#!/usr/bin/env python3
"""Generate a Quicksort program in Bork.

Why the program looks like it does
----------------------------------
Bork (as implemented today) has no way to write an array element:

  * `a[i] = v` is a parse error - `Stmt::Assign` in src/parser.lalrpop accepts a
    bare name on the left only, and docs/language.md says "There is no
    per-element `move` and no `a[i] = ...`".
  * parameters are by value (Copy crosses regions by copying; non-Copy `var`
    formals are moved into the callee), so no callee can mutate a caller's data.

So the sort buffer is N individual `var sN: i32` slots. `i32` is Copy, hence the
slots live in registers/stack and the whole sort does zero arena traffic
(docs/memory-model.md: arenas only own non-Copy payloads). Subscripting is a
generated if-tree on the runtime index - the only "indexing" the language offers
for such slots. Everything therefore lives in `main`.

Algorithm: 3-way (Dutch-flag) quicksort, median-of-three pivot, insertion-sort
cutoff, explicit work stack that always pushes the larger side (stack depth
O(log n), no deep recursion to blow a frame).
"""

import argparse
import random

STACK = 32


def slots_tree(names, idx_expr, leaf):
    """One-line nested if-tree over `names`, branching on the runtime `idx_expr`.

    `names` are (slot_number, base_name) pairs; the split compares against the
    slot number of the first name in the right half, so the tree is correct for
    any size (not just powers of two).
    """
    if len(names) == 1:
        return leaf(names[0][1])
    mid = len(names) // 2
    return ("if (" + idx_expr + " < " + str(names[mid][0]) + ") { "
            + slots_tree(names[:mid], idx_expr, leaf)
            + " } else { "
            + slots_tree(names[mid:], idx_expr, leaf)
            + " }")


def gen(values, stack=STACK, cutoff=13, rounds=None):
    n = len(values)
    # (slot_number, variable_name) pairs; the slot number is the tree's branch key
    big = [(k, "s" + str(k)) for k in range(n)]
    lo_slots = [(k, "st_lo" + str(k)) for k in range(stack)]
    hi_slots = [(k, "st_hi" + str(k)) for k in range(stack)]

    read_a = lambda idx: slots_tree(big, idx, lambda name: name)
    write_a = lambda idx, val: slots_tree(big, idx, lambda name: name + " = " + val)
    read_lo = lambda idx: slots_tree(lo_slots, idx, lambda name: name)
    read_hi = lambda idx: slots_tree(hi_slots, idx, lambda name: name)
    write_lo = lambda idx, val: slots_tree(lo_slots, idx, lambda name: name + " = " + val)
    write_hi = lambda idx, val: slots_tree(hi_slots, idx, lambda name: name + " = " + val)

    out = []
    out.append("// Generated by tools/gen_quicksort.py - do not edit by hand.")
    out.append("// 3-way quicksort, median-of-three pivot, insertion cutoff %d, %d elements." % (cutoff, n))
    out.append("// The buffer is %d Copy `i32` slots because Bork has no `a[i] = v`;" % n)
    out.append("// indexing is a generated if-tree (the only subscript the language has).")
    out.append("")
    out.append("fun main(): i32 {")

    out.append("    // input: a real [i32; %d] array, %d inline pseudo-randoms (seed 42)" % (n, n))
    out.append("    val input: [i32; %d] = [%s]" % (n, ", ".join(str(v) for v in values)))
    out.append("")
    out.append("    // sort buffer: %d Copy slots (registers/stack, no arena traffic)" % n)
    for k in range(n):
        out.append("    var s%d: i32 = input[%d]" % (k, k))
    out.append("")
    out.append("    // explicit work stack: push the larger side => depth <= O(log n)")
    for _, name in lo_slots + hi_slots:
        out.append("    var %s: i32 = 0" % name)
    out.append("    var sp = 0")
    out.append("    var steps = 0")
    out.append("    var peak = 0")
    out.append("")
    out.append("    st_lo0 = 0")
    out.append("    st_hi0 = %d" % (n - 1))
    out.append("    sp = 1")
    out.append("")
    if rounds is None:
        rounds = 4 * n
    out.append("    // `while (sp > 0)` spelled as a bounded for + guard")
    out.append("    for (round in 0..%d) {" % rounds)
    out.append("        if (sp > 0) {")
    out.append("            steps = steps + 1")
    out.append("            sp = sp - 1")
    out.append("            var lo: i32 = %s" % read_lo("sp"))
    out.append("            var hi: i32 = %s" % read_hi("sp"))
    out.append("            if (hi - lo < %d) {" % cutoff)
    out.extend(insertion_sort(read_a, write_a))
    out.append("            } else {")
    out.extend(partition(read_a, write_a, read_lo, read_hi, write_lo, write_hi, n))
    out.append("            }")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    // output")
    out.append("    println(%d)" % n)
    for _, name in big:
        out.append("    println(%s)" % name)
    out.append("    println(steps)")
    out.append("    println(peak)")
    out.append("    return 0")
    out.append("}")
    return "\n".join(out) + "\n"


def insertion_sort(read_a, write_a):
    i0, i1, i2, i3 = " " * 16, " " * 20, " " * 24, " " * 28
    return [
        i0 + "// insertion sort of a range shorter than the cutoff",
        i0 + "var i: i32 = lo + 1",
        i0 + "for (is_outer in 0..16) {",
        i1 + "if (i <= hi) {",
        i2 + "val key: i32 = %s" % read_a("i"),
        i2 + "var j: i32 = i - 1",
        i2 + "var going: i32 = 1",
        i2 + "for (is_inner in 0..16) {",
        i3 + "if (going == 1) {",
        i3 + "    if (j < lo) {",
        i3 + "        going = 0",
        i3 + "    } else {",
        i3 + "        val v: i32 = %s" % read_a("j"),
        i3 + "        if (v > key) {",
        i3 + "            %s" % write_a("j + 1", "v"),
        i3 + "            j = j - 1",
        i3 + "        } else {",
        i3 + "            going = 0",
        i3 + "        }",
        i3 + "    }",
        i3 + "}",
        i2 + "}",
        i2 + "%s" % write_a("j + 1", "key"),
        i2 + "i = i + 1",
        i1 + "}",
        i0 + "}",
    ]


def partition(read_a, write_a, read_lo, read_hi, write_lo, write_hi, n):
    i0, i1, i2, i3 = " " * 12, " " * 16, " " * 20, " " * 24
    median3 = ("if (pa < pb) { if (pb < pc) { pb } else { if (pa < pc) { pc } else { pa } } }"
               " else { if (pa < pc) { pa } else { if (pb < pc) { pc } else { pb } } }")
    return [
        i0 + "// 3-way (Dutch flag) partition, median-of-three pivot",
        i0 + "val mid: i32 = lo + (hi - lo) / 2",
        i0 + "val pa: i32 = %s" % read_a("lo"),
        i0 + "val pb: i32 = %s" % read_a("mid"),
        i0 + "val pc: i32 = %s" % read_a("hi"),
        i0 + "val pivot: i32 = " + median3,
        i0 + "var lt: i32 = lo",
        i0 + "var i: i32 = lo",
        i0 + "var j: i32 = hi",
        i0 + "for (p in 0..%d) {" % (n + 2),
        i1 + "if (i <= j) {",
        i2 + "val v: i32 = %s" % read_a("i"),
        i2 + "if (v < pivot) {",
        i3 + "%s" % write_a("i", read_a("lt")),
        i3 + "%s" % write_a("lt", "v"),
        i3 + "lt = lt + 1",
        i3 + "i = i + 1",
        i2 + "} else {",
        i3 + "if (v > pivot) {",
        i3 + "    %s" % write_a("i", read_a("j")),
        i3 + "    %s" % write_a("j", "v"),
        i3 + "    j = j - 1",
        i3 + "} else {",
        i3 + "    i = i + 1",
        i3 + "}",
        i2 + "}",
        i1 + "}",
        i0 + "}",
        i0 + "// [lo, lt) < pivot, [lt, i) == pivot, (j, hi] > pivot",
        i0 + "// push both sides - the larger one first, so the smaller is popped next",
        i0 + "// (LIFO order keeps the peak stack depth near log2 n)",
        i0 + "if (lt - lo > hi - j) {",
        i1 + "if (lt - lo > 1) {",
        i2 + "%s" % write_lo("sp", "lo"),
        i2 + "%s" % write_hi("sp", "lt - 1"),
        i2 + "sp = sp + 1",
        i2 + "if (sp > peak) { peak = sp }",
        i1 + "}",
        i1 + "if (hi - j > 1) {",
        i2 + "%s" % write_lo("sp", "j + 1"),
        i2 + "%s" % write_hi("sp", "hi"),
        i2 + "sp = sp + 1",
        i2 + "if (sp > peak) { peak = sp }",
        i1 + "}",
        i0 + "} else {",
        i1 + "if (hi - j > 1) {",
        i2 + "%s" % write_lo("sp", "j + 1"),
        i2 + "%s" % write_hi("sp", "hi"),
        i2 + "sp = sp + 1",
        i2 + "if (sp > peak) { peak = sp }",
        i1 + "}",
        i1 + "if (lt - lo > 1) {",
        i2 + "%s" % write_lo("sp", "lo"),
        i2 + "%s" % write_hi("sp", "lt - 1"),
        i2 + "sp = sp + 1",
        i2 + "if (sp > peak) { peak = sp }",
        i1 + "}",
        i0 + "}",
    ]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=100)
    parser.add_argument("--out", default="quicksort.bork")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--cutoff", type=int, default=13)
    parser.add_argument("--low", type=int, default=1)
    parser.add_argument("--high", type=int, default=999)
    parser.add_argument("--pattern", default="random",
                        choices=["random", "sorted", "reverse", "equal", "few"])
    args = parser.parse_args()

    rng = random.Random(args.seed)
    n = args.n
    if args.pattern == "random":
        values = [rng.randint(args.low, args.high) for _ in range(n)]
    elif args.pattern == "sorted":
        values = list(range(1, n + 1))
    elif args.pattern == "reverse":
        values = list(range(n, 0, -1))
    elif args.pattern == "equal":
        values = [7] * n
    else:  # "few": many duplicates out of a tiny alphabet
        values = [rng.randint(1, 5) for _ in range(n)]
    source = gen(values, cutoff=args.cutoff)
    with open(args.out, "w") as handle:
        handle.write(source)
    expected_path = args.out + ".expected"
    with open(expected_path, "w") as handle:
        handle.write("\n".join(str(v) for v in sorted(values)) + "\n")
    print("wrote %s (%d bytes, %d values, cutoff %d, pattern %s)"
          % (args.out, len(source), args.n, args.cutoff, args.pattern))
    print("expected written to " + expected_path)


if __name__ == "__main__":
    main()
